/**
 * Built-in categorization rules for common Canadian merchants. Matched against the NORMALIZED
 * merchant (see normalizeMerchant). Longer patterns win, so "COSTCO GAS" beats "COSTCO". Whole words only; a trailing
 * "*" makes the last word a prefix ("PHARMA*" matches "PHARMACY").
 * Your own corrections always take precedence over these.
 */
export interface SystemRule {
  pattern: string;
  category: string;
  /** Only match money in / money out */
  direction?: "in" | "out";
}

const r = (category: string, patterns: string[], direction?: "in" | "out"): SystemRule[] =>
  patterns.map((pattern) => ({ pattern, category, direction }));

